fn svg(name: &str) -> String {
    format!(
        r#"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{}</svg>"#,
        body(name)
    )
}

/// `<Icon name="search" />`
#[component]
pub fn Icon(#[prop(into)] name: String, #[prop(optional)] class: &'static str) -> impl IntoView {
    let cls = if class.is_empty() { "ico".to_string() } else { format!("ico {class}") };
    view! { <span class=cls inner_html=svg(&name)></span> }
}

/// Icon für eine Dateiart, eingefärbt per CSS-Klasse `kind-<art>`
#[component]
pub fn KindIcon(#[prop(into)] kind: String, #[prop(optional)] class: &'static str) -> impl IntoView {
    let cls = format!("ico kind kind-{kind} {class}");
    view! { <span class=cls inner_html=svg(&kind)></span> }
}
